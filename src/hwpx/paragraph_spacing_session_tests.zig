const std = @import("std");
const editor = @import("editor_session.zig");
const history_mod = @import("editor_history.zig");
test "HWPX paragraph spacing history saves combined properties and preserves redo after refusal" {
    const a = std.testing.allocator;
    const bytes = try std.Io.Dir.cwd().readFileAlloc(std.testing.io, "legacy/rust/crates/hwp-core/tests/fixtures/parashape.hwpx", a, .limited(4_000_000));
    defer a.free(bytes);
    var session = try editor.open(a, bytes, .{});
    defer session.deinit();
    const paragraph = session.sections[0].first_paragraph + 5;
    var history = try history_mod.History.init(&session, 8, 4_000_000);
    defer history.deinit();
    const spacing: history_mod.Command = .{ .kind = .paragraph_spacing, .paragraph = paragraph, .start = 0, .deleted = 0, .inserted = "", .paragraph_spacing = .{ .kind = 0, .value = 200 } };
    try std.testing.expect(try history.apply(&session, spacing));
    try std.testing.expect(!try history.apply(&session, spacing));
    var margins = spacing;
    margins.kind = .paragraph_margins;
    margins.paragraph_margins = .{ .indent = -720 };
    try std.testing.expect(try history.apply(&session, margins));
    var alignment = spacing;
    alignment.kind = .paragraph_alignment;
    alignment.paragraph_alignment = .CENTER;
    try std.testing.expect(try history.apply(&session, alignment));
    const saved = try session.save();
    defer a.free(saved);
    var reopened = try editor.open(a, saved, .{});
    defer reopened.deinit();
    const id = try reopened.paragraphShapeId(0, paragraph);
    const shapes = try reopened.paragraphShapes();
    defer @import("paragraph_display_resources.zig").deinit(a, shapes);
    var found = false;
    for (shapes) |shape| if (shape.id == id) {
        found = true;
        try std.testing.expectEqualStrings("CENTER", shape.horizontal.?);
        try std.testing.expectEqual(@as(?i64, -720), shape.margins[0].?.value);
        try std.testing.expectEqual(@as(?i64, 200), shape.spacing.?.value);
    };
    try std.testing.expect(found);
    for (0..3) |_| try std.testing.expect(try history.undo(&session));
    const original = try session.save();
    defer a.free(original);
    try std.testing.expectEqualSlices(u8, bytes, original);
    var invalid = spacing;
    invalid.paragraph_spacing.value = 501;
    try std.testing.expectError(error.InvalidParagraphSpacing, history.apply(&session, invalid));
    for (0..3) |_| try std.testing.expect(try history.redo(&session));
    const redone = try session.save();
    defer a.free(redone);
    try std.testing.expectEqualSlices(u8, saved, redone);
}
