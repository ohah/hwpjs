const std = @import("std");
test "chart Session keeps text edits and checkpoint owns numeric values" {
    const a = std.testing.allocator;
    const input = std.Io.Dir.cwd().readFileAlloc(std.testing.io, "reference/rhwp/samples/chart/가로막대형/3차원누적가로막대형.hwpx", a, .limited(4000000)) catch |err| switch (err) {
        error.FileNotFound => return error.SkipZigTest,
        else => return err,
    };
    defer a.free(input);
    var session = try @import("editor_session.zig").open(a, input, .{});
    defer session.deinit();
    var wrapper: ?usize = null;
    for (session.sections[0].tree.elements, 0..) |_, node| if (@import("run_switch_anchor.zig").supported(&session.sections[0].tree, node)) {
        wrapper = node;
        break;
    };
    var archive = try @import("../zip/archive.zig").open(a, input, .{});
    defer archive.deinit();
    const xml = try archive.decode(archive.find("Chart/chart1.xml").?, 4000000);
    defer a.free(xml);
    var tree = try @import("chart_tree.zig").parse(a, xml, 0, .{});
    defer tree.deinit(a);
    var points = try @import("chart_point_values.zig").collect(a, &tree, .{});
    defer points.deinit(a);
    var ordinal: ?usize = null;
    for (points.points, 0..) |point, index| if (point.kind == .numeric_cache) {
        ordinal = index;
        break;
    };
    try std.testing.expect(try session.spliceAnchored(0, 1, 0, 0, "본문😀<&"));
    const before = try session.save();
    defer a.free(before);
    var checkpoint = try @import("editor_checkpoint.zig").capture(&session, 4000000);
    defer checkpoint.deinit();
    try std.testing.expect(try session.setChartNumericPoint(0, wrapper.?, ordinal.?, "314.159"));
    try std.testing.expectEqualStrings("314.159", session.chart_resources.entries.items[0].points.points[ordinal.?].value);
    const chart_nodes = try @import("chart_current_snapshot.zig").nodes(a, &session, 0);
    defer a.free(chart_nodes);
    try std.testing.expectEqualSlices(usize, &.{wrapper.?}, chart_nodes);
    var snapshot = try @import("chart_current_snapshot.zig").read(a, &session, 0, wrapper.?);
    defer snapshot.deinit(a);
    try std.testing.expectEqualStrings("314.159", snapshot.values.points[ordinal.?].value);
    try std.testing.expectEqual(snapshot.values.points.len, snapshot.bindings.len);
    try std.testing.expectEqual(@import("chart_point_roles.zig").Role.value, snapshot.bindings[ordinal.?].role);
    try std.testing.expect(snapshot.bindings[ordinal.?].series_node != null);
    try std.testing.expect(snapshot.values.points[ordinal.?].value.ptr != session.chart_resources.entries.items[0].points.points[ordinal.?].value.ptr);
    const changed = try session.save();
    defer a.free(changed);
    var reopened = try @import("editor_session.zig").open(a, changed, .{});
    defer reopened.deinit();
    const text = try reopened.anchorText(0, 1);
    defer a.free(text);
    try std.testing.expectEqualStrings("본문😀<&\xef\xbf\xbc", text);
    try std.testing.expect(!try session.setChartNumericPoint(0, wrapper.?, ordinal.?, "314.159"));
    try std.testing.expectError(error.InvalidChartNumericValue, session.setChartNumericPoint(0, wrapper.?, ordinal.?, "NaN"));
    const unchanged = try session.save();
    defer a.free(unchanged);
    try std.testing.expectEqualSlices(u8, changed, unchanged);
    try checkpoint.exchange(&session);
    const undone = try session.save();
    defer a.free(undone);
    try std.testing.expectEqualSlices(u8, before, undone);
    try checkpoint.exchange(&session);
    const redone = try session.save();
    defer a.free(redone);
    try std.testing.expectEqualSlices(u8, changed, redone);
    try std.testing.expectEqualSlices(u8, input, session.source);
    const History = @import("editor_history.zig").History;
    var history = try History.init(&session, 8, 4000000);
    defer history.deinit();
    const Command = @import("editor_history.zig").Command;
    const command: Command = .{ .kind = .chart_numeric_point, .paragraph = 0, .start = 0, .deleted = 0, .inserted = "6.70", .chart_node = wrapper.?, .chart_point = ordinal.? };
    try std.testing.expect(try history.apply(&session, command));
    const history_changed = try session.save();
    defer a.free(history_changed);
    try std.testing.expect(try history.undo(&session));
    var invalid = command;
    invalid.inserted = "NaN";
    try std.testing.expectError(error.InvalidChartNumericValue, history.apply(&session, invalid));
    var invalid_command = command;
    invalid_command.start = 1;
    try std.testing.expectError(error.InvalidChartPointCommand, history.apply(&session, invalid_command));
    var noop_command = command;
    noop_command.inserted = "314.159";
    try std.testing.expect(!try history.apply(&session, noop_command));
    try std.testing.expectError(error.InvalidChartNumericValue, history.applyBatch(&session, &.{ command, invalid }));
    const rolled_back = try session.save();
    defer a.free(rolled_back);
    try std.testing.expectEqualSlices(u8, changed, rolled_back);
    try std.testing.expect(try history.redo(&session));
    const history_redone = try session.save();
    defer a.free(history_redone);
    try std.testing.expectEqualSlices(u8, history_changed, history_redone);
}
