const std = @import("std");
const editor = @import("editor_session.zig");
const History = @import("editor_history.zig").History;
const eq = @import("equation_insert.zig");
test "HWPX inline object managed equation parked history preserves failed redo and Unicode" {
    const a = std.testing.allocator;
    const input = try @import("../new_document/hwpx.zig").create(a);
    defer a.free(input);
    var session = try editor.open(a, input, .{});
    defer session.deinit();
    session.history_delta_managed = true;
    var history = try History.initV2(&session, .{});
    defer history.deinit();
    try std.testing.expect(try history.apply(&session, .{ .paragraph = 1, .start = 0, .deleted = 0, .inserted = "A😀B" }));
    const before = try session.save();
    defer a.free(before);
    var hash: [32]u8 = undefined;
    std.crypto.hash.sha2.Sha256.hash(before, &hash, .{});
    const req: eq.Request = .{ .expected_source_sha256 = hash, .target = .{ .section = 0, .paragraph = 1, .unit = 1, .expected_text = "A😀B" }, .script = "x^2 + 한😀", .width = 2400, .height = 1200, .base_line = 80, .base_unit = 1000, .version = "Equation Version 60", .font = "HYhwpEQ" };
    const revision = history.revision();
    try std.testing.expect(try history.apply(&session, .{ .kind = .equation_insert, .paragraph = 1, .start = 1, .deleted = 0, .inserted = "", .equation_insert = &req }));
    const after = try session.save();
    defer a.free(after);
    var reopened = try editor.open(a, after, .{});
    defer reopened.deinit();
    const sources = try @import("equation_script_sources.zig").read(a, &reopened, 0);
    defer a.free(sources);
    try std.testing.expectEqual(@as(usize, 1), sources.len);
    const script = try reopened.equationScript(0, sources[0].node);
    defer a.free(script);
    try std.testing.expectEqualStrings(req.script, script);
    try std.testing.expect(try history.undo(&session));
    try std.testing.expectEqual(revision, history.revision());
    const undone = try session.save();
    defer a.free(undone);
    try std.testing.expectEqualSlices(u8, before, undone);
    var stale = req;
    stale.expected_source_sha256[0] ^= 1;
    const serial = session.mutation_serial;
    try std.testing.expectError(error.SourceHashMismatch, history.apply(&session, .{ .kind = .equation_insert, .paragraph = 1, .start = 1, .deleted = 0, .inserted = "", .equation_insert = &stale }));
    try std.testing.expectEqual(serial, session.mutation_serial);
    try std.testing.expectEqual(revision, history.revision());
    try std.testing.expect(try history.redo(&session));
    const redone = try session.save();
    defer a.free(redone);
    try std.testing.expectEqualSlices(u8, after, redone);
}
