const std = @import("std");
const edit = @import("style_preservation.zig");
test "HWP5 paragraph alignment session saves resources and restores history" {
    const a = std.testing.allocator;
    const bytes = try std.Io.Dir.cwd().readFileAlloc(std.testing.io, "legacy/rust/crates/hwp-core/tests/fixtures/parashape.hwp", a, .limited(4_000_000));
    defer a.free(bytes);
    const session = try edit.Session.open(a, bytes);
    defer session.close();
    const original_id = try session.paragraphShapeId(0, 0);
    const original_count = session.paragraphShapeCount();
    var history = try @import("editor_history.zig").History.init(a, session, 8, 4_000_000);
    defer history.deinit();
    const command: edit.Command = .{ .set_paragraph_alignment = .{ .section = 0, .paragraph = 0, .alignment = 3 } };
    try std.testing.expect(try history.apply(session, command));
    try std.testing.expectEqual(original_count + 1, session.paragraphShapeCount());
    const id = try session.paragraphShapeId(0, 0);
    try std.testing.expectEqual(original_count, id);
    const shapes = try session.paragraphShapes(a);
    defer a.free(shapes);
    try std.testing.expectEqual(@as(u3, 3), shapes[id].alignment);
    try std.testing.expectError(error.LayoutReflowRequired, session.save(a, .{}));
    const changed = try session.save(a, .{ .allow_stale_layout = true });
    defer a.free(changed.bytes);
    const reopened = try edit.Session.open(a, changed.bytes);
    defer reopened.close();
    try std.testing.expectEqual(id, try reopened.paragraphShapeId(0, 0));
    try std.testing.expectEqual(original_count + 1, reopened.paragraphShapeCount());
    try std.testing.expect(try history.undo(session));
    try std.testing.expectEqual(original_id, try session.paragraphShapeId(0, 0));
    try std.testing.expectEqual(original_count, session.paragraphShapeCount());
    const restored = try session.save(a, .{});
    defer a.free(restored.bytes);
    try std.testing.expectEqualSlices(u8, bytes, restored.bytes);
    try std.testing.expectError(error.InvalidParagraphAlignment, history.apply(session, .{ .set_paragraph_alignment = .{ .section = 0, .paragraph = 0, .alignment = 6 } }));
    history.max_checkpoint_bytes = try session.checkpointSize(4_000_000);
    try std.testing.expectError(error.LimitExceeded, history.apply(session, command));
    try std.testing.expectEqual(original_count, session.paragraphShapeCount());
    try std.testing.expectEqual(original_id, try session.paragraphShapeId(0, 0));
    history.max_checkpoint_bytes = 4_000_000;
    try std.testing.expect(try history.redo(session));
    try std.testing.expect(!try history.apply(session, command));
    const redone = try session.save(a, .{ .allow_stale_layout = true });
    defer a.free(redone.bytes);
    try std.testing.expectEqualSlices(u8, changed.bytes, redone.bytes);
}

test "HWP5 paragraph margin session composes alignment saves and restores history" {
    const a = std.testing.allocator;
    const bytes = try std.Io.Dir.cwd().readFileAlloc(std.testing.io, "legacy/rust/crates/hwp-core/tests/fixtures/parashape.hwp", a, .limited(4_000_000));
    defer a.free(bytes);
    const session = try edit.Session.open(a, bytes);
    defer session.close();
    var history = try @import("editor_history.zig").History.init(a, session, 8, 4_000_000);
    defer history.deinit();
    const command: edit.Command = .{ .set_paragraph_margins = .{ .section = 0, .paragraph = 5, .margins = .{ .indent = -720, .before = 0, .left = 1000 } } };
    try std.testing.expect(try history.apply(session, command));
    const id = try session.paragraphShapeId(0, 5);
    const shapes = try session.paragraphShapes(a);
    defer a.free(shapes);
    try std.testing.expectEqual(@as(u3, 2), shapes[id].alignment);
    try std.testing.expectEqual(@as(i32, -720), shapes[id].indent);
    try std.testing.expectEqual(@as(i32, 1000), shapes[id].left);
    try std.testing.expectEqual(@as(i32, 0), shapes[id].before);
    try std.testing.expect(!try history.apply(session, command));
    try std.testing.expect(try history.apply(session, .{ .set_paragraph_alignment = .{ .section = 0, .paragraph = 5, .alignment = 3 } }));
    const centered = try session.paragraphShapeId(0, 5);
    const saved = try session.save(a, .{ .allow_stale_layout = true });
    defer a.free(saved.bytes);
    const reopened = try edit.Session.open(a, saved.bytes);
    defer reopened.close();
    const reopened_shapes = try reopened.paragraphShapes(a);
    defer a.free(reopened_shapes);
    try std.testing.expectEqual(@as(u3, 3), reopened_shapes[centered].alignment);
    try std.testing.expectEqual(@as(i32, -720), reopened_shapes[centered].indent);
    try std.testing.expectEqual(@as(i32, 1000), reopened_shapes[centered].left);
    try std.testing.expect(try history.undo(session));
    try std.testing.expectEqual(id, try session.paragraphShapeId(0, 5));
    try std.testing.expect(try history.undo(session));
    const restored = try session.save(a, .{});
    defer a.free(restored.bytes);
    try std.testing.expectEqualSlices(u8, bytes, restored.bytes);
    try std.testing.expect(try history.redo(session));
    try std.testing.expect(try history.redo(session));
    const redone = try session.save(a, .{ .allow_stale_layout = true });
    defer a.free(redone.bytes);
    try std.testing.expectEqualSlices(u8, saved.bytes, redone.bytes);
}
