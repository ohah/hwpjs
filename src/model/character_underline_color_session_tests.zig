const std = @import("std");
test "underline color native sessions preserve mixed properties save reopen undo redo" {
    const a = std.testing.allocator;
    const binary_input = try std.Io.Dir.cwd().readFileAlloc(std.testing.io, "legacy/rust/crates/hwp-core/tests/fixtures/parashape.hwp", a, .limited(4_000_000));
    defer a.free(binary_input);
    const binary = try @import("../hwp5/edit/style_preservation.zig").Session.open(a, binary_input);
    defer binary.close();
    var binary_history = try @import("../hwp5/edit/editor_history.zig").History.init(a, binary, 8, 8_000_000);
    defer binary_history.deinit();
    const command: @import("../hwp5/edit/style_preservation.zig").Command = .{ .set_character_properties = .{ .section = 0, .paragraph = 5, .start_unit = 0, .end_unit = 1, .properties = .{ .underline_color = 0x123456 } } };
    try std.testing.expect(try binary_history.apply(binary, command));
    try std.testing.expect(!try binary_history.apply(binary, command));
    const binary_saved = try binary.save(a, .{ .allow_stale_layout = true });
    defer a.free(binary_saved.bytes);
    const reopened = try @import("../hwp5/edit/style_preservation.zig").Session.open(a, binary_saved.bytes);
    defer reopened.close();
    try reopened.apply(command);
    const reopened_saved = try reopened.save(a, .{ .allow_stale_layout = true });
    defer a.free(reopened_saved.bytes);
    try std.testing.expectEqualSlices(u8, binary_saved.bytes, reopened_saved.bytes);
    try std.testing.expect(try binary_history.undo(binary));
    const original = try binary.save(a, .{ .allow_stale_layout = true });
    defer a.free(original.bytes);
    try std.testing.expectEqualSlices(u8, binary_input, original.bytes);
    try std.testing.expect(try binary_history.redo(binary));
    const redone = try binary.save(a, .{ .allow_stale_layout = true });
    defer a.free(redone.bytes);
    try std.testing.expectEqualSlices(u8, binary_saved.bytes, redone.bytes);

    const xml_input = try std.Io.Dir.cwd().readFileAlloc(std.testing.io, "legacy/rust/crates/hwp-core/tests/fixtures/charshape.hwpx", a, .limited(4_000_000));
    defer a.free(xml_input);
    var xml = try @import("../hwpx/editor_session.zig").open(a, xml_input, .{});
    defer xml.deinit();
    var xml_history = try @import("../hwpx/editor_history.zig").History.init(&xml, 8, 8_000_000);
    defer xml_history.deinit();
    const XmlCommand = @import("../hwpx/editor_history.zig").Command;
    var request: XmlCommand = .{ .kind = .character_properties, .paragraph = 2, .start = 0, .deleted = 1, .inserted = "", .character_properties = .{ .underline_color = 0x123456 } };
    try std.testing.expect(try xml_history.apply(&xml, request));
    try std.testing.expect(!try xml_history.apply(&xml, request));
    request.character_properties = .{ .size = 2400 };
    try std.testing.expect(try xml_history.apply(&xml, request));
    request.character_properties = .{ .underline_kind = .top };
    try std.testing.expect(try xml_history.apply(&xml, request));
    const rows = try @import("../hwpx/character_underline_snapshot.zig").readFull(&xml);
    defer @import("../hwpx/character_underline_snapshot.zig").deinit(a, rows);
    const spans = try @import("../hwpx/character_style_snapshot.zig").read(&xml, 0, 2);
    defer a.free(spans);
    var found = false;
    for (rows) |row| if (row.id == spans[0].char_shape_id) {
        try std.testing.expectEqualStrings("#123456", row.color.?);
        try std.testing.expectEqual(@import("document.zig").CharacterUnderlineKind.top, row.kind.?);
        found = true;
    };
    try std.testing.expect(found);
    const saved = try xml.save();
    defer a.free(saved);
    var xml_reopened = try @import("../hwpx/editor_session.zig").open(a, saved, .{});
    defer xml_reopened.deinit();
    try std.testing.expect(!try xml_reopened.setCharacterProperties(0, 2, 0, 1, .{ .underline_color = 0x123456 }));
    try std.testing.expect(try xml_history.undo(&xml));
    request.character_properties = .{ .underline_color = 0x1000000 };
    try std.testing.expectError(error.InvalidCharacterColor, xml_history.apply(&xml, request));
    try std.testing.expect(try xml_history.redo(&xml));
    const xml_redone = try xml.save();
    defer a.free(xml_redone);
    try std.testing.expectEqualSlices(u8, saved, xml_redone);
    for (0..3) |_| try std.testing.expect(try xml_history.undo(&xml));
    const xml_original = try xml.save();
    defer a.free(xml_original);
    try std.testing.expectEqualSlices(u8, xml_input, xml_original);
}
