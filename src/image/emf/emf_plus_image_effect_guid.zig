const entries = [_]struct { kind: Kind, bytes: [16]u8 }{
    .{ .kind = .blur, .bytes = blur },
    .{ .kind = .brightness_contrast, .bytes = brightness_contrast },
    .{ .kind = .color_balance, .bytes = color_balance },
    .{ .kind = .color_curve, .bytes = color_curve },
    .{ .kind = .color_lookup_table, .bytes = color_lookup_table },
    .{ .kind = .color_matrix, .bytes = color_matrix },
    .{ .kind = .hue_saturation_lightness, .bytes = hue_saturation_lightness },
    .{ .kind = .levels, .bytes = levels },
    .{ .kind = .red_eye_correction, .bytes = red_eye_correction },
    .{ .kind = .sharpen, .bytes = sharpen },
    .{ .kind = .tint, .bytes = tint },
};

pub fn classify(bytes: [16]u8) !Kind {
    for (entries) |entry| if (std.mem.eql(u8, &bytes, &entry.bytes)) return entry.kind;
    return error.InvalidEmfPlusImageEffectGuid;
}

test "EMF+ image effect GUIDs use packet byte order and are unique" {
    for (entries, 0..) |entry, i| {
        try std.testing.expectEqual(entry.kind, try classify(entry.bytes));
        for (entries[i + 1 ..]) |other|
            try std.testing.expect(!std.mem.eql(u8, &entry.bytes, &other.bytes));
    }
    var unknown = blur;
    unknown[15] ^= 1;
    try std.testing.expectError(error.InvalidEmfPlusImageEffectGuid, classify(unknown));
}
