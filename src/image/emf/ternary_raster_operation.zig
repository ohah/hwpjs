pub const Operation = struct {
    raw: u32,
    index: u8,
    operation_code: u16,

    pub fn requiresSource(self: Operation) bool {
        const truth = self.index;
        inline for (0..2) |pattern| inline for (0..2) |destination| {
            const without_source = destination + pattern * 4;
            const with_source = without_source + 2;
            if ((truth >> without_source) & 1 != (truth >> with_source) & 1) return true;
        };
        return false;
    }
};

pub fn parse(raw: u32) !Operation {
    // The operation index is a zero-extended 8-bit value in the high word.
    if (raw & 0xff00_0000 != 0) return error.InvalidEmfTernaryRasterOperationIndex;
    const index: u8 = @truncate(raw >> 16);
    const operation_code: u16 = @truncate(raw);
    const expected = operation_codes[index] orelse return error.InvalidEmfTernaryRasterOperation;
    if (operation_code != expected) return error.InvalidEmfTernaryRasterOperation;
    return .{ .raw = raw, .index = index, .operation_code = operation_code };
}

test "ternary raster operation preserves wire code and derives source dependency from truth table" {
    const source_copy = try parse(0x00cc0020);
    try std.testing.expectEqual(@as(u8, 0xcc), source_copy.index);
    try std.testing.expectEqual(@as(u16, 0x0020), source_copy.operation_code);
    try std.testing.expect(source_copy.requiresSource());
    try std.testing.expect(!(try parse(0x00f00021)).requiresSource()); // PATCOPY
    try std.testing.expect(!(try parse(0x00550009)).requiresSource()); // DSTINVERT
    try std.testing.expectError(error.InvalidEmfTernaryRasterOperationIndex, parse(0x01cc0020));
    try std.testing.expectError(error.InvalidEmfTernaryRasterOperation, parse(0x00ccffff));
    try std.testing.expectError(error.InvalidEmfTernaryRasterOperation, parse(0x005d0000));
    _ = try parse(0x00390604); // Official HTML omits one leading zero.
    _ = try parse(0x00570389); // Official HTML contains one extra zero.
}

test "ternary raster operation table contains exactly the 250 published values" {
    var published: usize = 0;
    for (operation_codes) |code| if (code != null) {
        published += 1;
    };
    try std.testing.expectEqual(@as(usize, 250), published);
}

test "exactly sixteen ternary truth tables are independent of source" {
    var independent: usize = 0;
    for (operation_codes, 0..) |code, index| if (code) |value| {
        const operation = try parse((@as(u32, @intCast(index)) << 16) | value);
        if (!operation.requiresSource()) independent += 1;
    };
    try std.testing.expectEqual(@as(usize, 16), independent);
}
