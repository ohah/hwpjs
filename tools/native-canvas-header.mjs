/** Generate only the additive Canvas header from the Native contract/signatures. */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
export function generateCanvasHeader(contract, abi) {
  const body = /pub const CapabilityInfo = extern struct \{([\s\S]*?)\n\};/.exec(contract)?.[1];
  if (!body) throw Error('NativeCapabilityLayoutMissing');
  const fields = [...body.matchAll(/^\s*(\w+): (u32),$/gm)];
  if (fields.length !== body.split('\n').filter((x) => x.trim()).length)
    throw Error('NativeCapabilityLayoutUnsupported');
  const inventory = /pub const canvas_exports = \[_\]CanvasExport\{([\s\S]*?)\n\};/.exec(
    contract,
  )?.[1];
  if (!inventory) throw Error('NativeCapabilityExportInventoryInvalid');
  const records = inventory.split('\n').filter((line) => line.trim());
  const entries = records.map((line) => {
    const match =
      /^\s*\.\{ \.name = "(hwp_native_\w+)", \.guard = \.(always|snapshot|render) \},$/.exec(line);
    if (!match) throw Error('NativeCapabilityExportInventoryInvalid');
    return match;
  });
  if (!entries.length || new Set(entries.map((x) => x[1])).size !== entries.length)
    throw Error('NativeCapabilityExportInventoryInvalid');
  const types = new Map([
    ['?*Bridge', 'HwpNativeBridge *'],
    ['Token', 'HwpNativeToken'],
    ['?*Buffer', 'HwpNativeBuffer *'],
    ['?*CapabilityInfo', 'HwpNativeCapabilityInfo *'],
    ['usize', 'size_t'],
    ['u32', 'uint32_t'],
  ]);
  const constants = [
    ...contract.matchAll(
      /pub const (abi_version|capability_version|snapshot_version|render_sources_version|snapshot_v2|render_sources|history_v2): u32 = (\d+);/g,
    ),
  ];
  if (constants.length !== 7) throw Error('NativeCapabilityConstantsUnsupported');
  const lines = [
    '// Generated by tools/native-canvas-header.mjs; do not edit.',
    '#pragma once',
    '#include "hwp_native.h"',
    '#ifdef __cplusplus',
    'extern "C" {',
    '#endif',
    'typedef struct {',
    ...fields.map((x) => '  uint32_t ' + x[1] + ';'),
    '} HwpNativeCapabilityInfo;',
    'enum {',
    ...constants.map((x) => '  HWP_NATIVE_CAPS_' + x[1].toUpperCase() + ' = ' + x[2] + ','),
    '};',
  ];
  for (const [, name, guard] of entries) {
    const escaped = name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const match = new RegExp('pub export fn ' + escaped + '\\(([^\\n]*?)\\) Status \\{').exec(abi);
    if (!match) throw Error('NativeCapabilitySignatureMissing:' + name);
    const args = match[1].split(',').map((arg) => {
      const pair = /^\s*\w+:\s*(.*?)\s*$/.exec(arg);
      const type = pair && types.get(pair[1]);
      if (!type) throw Error('NativeCapabilityTypeUnsupported:' + arg);
      return type;
    });
    if (guard !== 'always')
      lines.push(
        '#ifdef ' +
          (guard === 'snapshot' ? 'HWPJS_NATIVE_SHARED_SNAPSHOT' : 'HWPJS_NATIVE_RENDER_SOURCES'),
      );
    lines.push('HwpNativeStatus ' + name + '(' + args.join(', ') + ');');
    if (guard !== 'always') lines.push('#endif');
  }
  lines.push('#ifdef __cplusplus', '}', '#endif', '');
  return lines.join('\n');
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2),
    check = args.includes('--check');
  const output = args.filter((x) => x !== '--check');
  if (output.length !== 1) throw Error('Usage: native-canvas-header.mjs [--check] OUTPUT');
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  const bytes = generateCanvasHeader(
    readFileSync(join(root, 'src/native/abi_contract.zig'), 'utf8'),
    readFileSync(join(root, 'src/native/abi.zig'), 'utf8'),
  );
  if (check) {
    if (readFileSync(output[0], 'utf8') !== bytes) throw Error('NativeCanvasHeaderStale');
  } else writeFileSync(output[0], bytes);
}
