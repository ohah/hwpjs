import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { formulaAtParagraph } from "../../web/preview/formula-selection.mjs";

test("HWP5 Worker formula panel handles current definitions history refusals and saved reopen without unlocking result text", async t => {
  const previousSelf = globalThis.self, previousFetch = globalThis.fetch, replies = [];
  const wasm = readFileSync(process.env.HWPJS_TEST_WASM ?? "zig-out/bin/hwpjs.wasm");
  globalThis.self = { postMessage(value) { replies.push(value); } };
  globalThis.fetch = async () => new Response(wasm);
  t.after(() => { globalThis.fetch = previousFetch; if (previousSelf === undefined) delete globalThis.self; else globalThis.self = previousSelf; });
  await import(`../../web/preview/reader-worker.mjs?formula-definition=${Date.now()}`);
  const send = async data => { await self.onmessage({ data }); assert.equal(replies.length, 1); return replies.shift(); };
  const input = readFileSync("legacy/rust/crates/hwp-core/tests/fixtures/chart.hwp");
  const loaded = await send({ kind: "load", format: "hwp5", bytes: input });
  assert.equal(loaded.error, undefined); assert.equal(loaded.content.formulaDefinitionAvailable, true);
  assert.deepEqual(loaded.content.formulaErrors, []); assert.equal(loaded.content.formulas.length, 13);
  const first = loaded.content.formulas[0], command = { kind: "formula-definition", section: first.section, beginElement: first.beginElement, formula: "=AVG(B?:E?)" };
  assert.equal(formulaAtParagraph(loaded.content, { section: 0, paragraph: 23 }), first);
  assert.equal((await send(command)).error, "EditorNotOpen");
  assert.equal((await send({ kind: "enable" })).error, undefined);
  const protectedResult = await send({ kind: "splice", section: 0, paragraph: 23, startUnit: 8, endUnit: 8, text: "X" });
  assert.equal(protectedResult.error, "ReadOnlyFormulaResult");
  assert.equal(protectedResult.applied, false);
  assert.deepEqual(Buffer.from((await send({ kind: "save" })).bytes), input);
  const changed = await send(command); assert.equal(changed.error, undefined);
  assert.equal(changed.content.formulas[0].formula, "=AVG(B?:E?)");
  assert.equal(changed.content.formulas[0].last_result, "16.875");
  const saved = await send({ kind: "save", allowStaleLayout: true }); assert.equal(saved.error, undefined);
  assert.equal((await send({ kind: "undo" })).content.formulas[0].formula, first.formula);
  const refused = await send({ ...command, formula: "=SUM(Z999:Z1000)" });
  assert.equal(refused.error, "FormulaReferenceOutOfBounds"); assert.equal(refused.applied, false);
  assert.deepEqual(Buffer.from((await send({ kind: "save" })).bytes), input);
  assert.equal((await send({ kind: "redo" })).content.formulas[0].last_result, "16.875");
  const reopened = await send({ kind: "load", format: "hwp5", bytes: saved.bytes });
  assert.equal(reopened.error, undefined); assert.equal(reopened.content.formulas[0].formula, "=AVG(B?:E?)");
  assert.equal(reopened.content.formulas[0].derived, false);
  const ambiguous = structuredClone(reopened.content);
  ambiguous.formulas.push(structuredClone(ambiguous.formulas[0]));
  assert.equal(formulaAtParagraph(ambiguous, { section: 0, paragraph: 23 }), null);
});
