import base64
import copy
import io
import json
from pathlib import Path
import subprocess
import sys
import unittest
import zipfile

ORACLE = Path(__file__).resolve().parents[2] / 'tools/hwpx-field-title-save-oracle.py'
LEGACY = ORACLE.with_name('hwpx-character-format-oracle.py')
P = 'http://www.hancom.co.kr/hwpml/2011/paragraph'
XML = f'''<?xml version="1.0"?><?audit keep?><!--outside--><s:sec xmlns:s="http://www.hancom.co.kr/hwpml/2011/section" xmlns:p="{P}"><p:p><p:run charPrIDRef='1'><p:t>X</p:t><p:ctrl><p:fieldBegin id='1' type='CLICK_HERE' dirty='0'/></p:ctrl><p:t>A</p:t><p:ctrl><p:fieldEnd beginIDRef='1'/></p:ctrl><p:t/><p:t>B<p:titleMark ignore='1'/>C</p:t></p:run><p:linesegarray><p:lineseg vertpos="123"/></p:linesegarray></p:p><p:p><!--inner--><p:run charPrIDRef='1'><p:t>other</p:t></p:run></p:p></s:sec>'''
# Literal synthetic expected after, not generated by the checker or product.
FORMATTED = XML.replace("charPrIDRef='1'", "charPrIDRef='2'", 1).replace("<p:t/><p:t>B", "</p:run><p:run charPrIDRef='1'><p:t/></p:run><p:run charPrIDRef='2'><p:t>B").replace('<p:linesegarray><p:lineseg vertpos="123"/></p:linesegarray>', '')
SPLICED = FORMATTED.replace('>B<p:titleMark', '>BY<p:titleMark').replace("ignore='1'/>C", "ignore='1'/>")
HEADER = '<h:head xmlns:h="http://www.hancom.co.kr/hwpml/2011/head"><h:charPr id="1"/><h:charPr id="2"/></h:head>'


def packed(xml, payload=b'opaque', comment=b'keep', duplicate=False):
    output = io.BytesIO()
    with zipfile.ZipFile(output, 'w') as z:
        z.comment = comment
        for name, data in [('Contents/header.xml', HEADER), ('Contents/section0.xml', xml), ('BinData/keep.bin', payload)]:
            info = zipfile.ZipInfo(name, (2020, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            z.writestr(info, data)
        if duplicate:
            z.writestr('BinData/keep.bin', b'other')
    return base64.b64encode(output.getvalue()).decode()


def request():
    return dict(mode='per-text-field-title-format', before=packed(XML), after=packed(FORMATTED), paragraph=1, startUnit=0, endUnit=4, charShapeId=2, invalidateLineSegments=True)


class Evidence(unittest.TestCase):
    def check(self, data, reason=None, script=ORACLE):
        for flags in ([], ['-O']):
            with self.subTest(flags=flags):
                result = subprocess.run([sys.executable, *flags, str(script)], input=json.dumps(data), text=True, capture_output=True)
                if reason is None:
                    self.assertEqual(result.returncode, 0, result.stderr)
                    self.assertIs(json.loads(result.stdout)['verified'], True)
                else:
                    self.assertEqual(result.returncode, 1, result.stderr)
                    self.assertIn('ValueError: ' + reason, result.stderr)

    def test_format_and_reused_legacy(self):
        self.check(request())
        self.check(dict(request(), mode='anchor-format'), script=LEGACY)

    def test_splice(self):
        self.check(dict(request(), mode='per-text-format-and-replace', after=packed(SPLICED), leftBefore='B', rightBefore='C', inserted='Y', deleteUnits=1))

    def test_wrong_valid_style(self):
        self.check(dict(request(), charShapeId=1), 'whole target XML differs')
        self.check(dict(request(), mode='anchor-format', charShapeId=1), 'text/style/attribute signature mismatch', LEGACY)

    def test_wrong_expected_insert(self):
        self.check(dict(request(), mode='per-text-format-and-replace', after=packed(SPLICED), leftBefore='B', rightBefore='C', inserted='Z', deleteUnits=1), 'whole target XML differs')

    def test_dirty(self):
        self.check(dict(request(), after=packed(FORMATTED.replace("dirty='0'", "dirty='1'"))), 'whole target XML differs')

    def test_marker_side(self):
        self.check(dict(request(), after=packed(FORMATTED.replace("B<p:titleMark ignore='1'/>C", "BC<p:titleMark ignore='1'/>"))), 'whole target XML differs')

    def test_binary_payload(self):
        self.check(dict(request(), after=packed(FORMATTED, payload=b'changed')), 'non-target ZIP payload')

    def test_other_paragraph(self):
        self.check(dict(request(), after=packed(FORMATTED.replace('other', 'corrupt'))), 'whole target XML differs')

    def test_extra_target_attribute(self):
        self.check(dict(request(), after=packed(FORMATTED.replace('<p:p>', '<p:p extra="lost">', 1))), 'whole target XML differs')

    def test_comments_and_pi(self):
        for source, target in [('<!--outside-->', '<!--changed-->'), ('<?audit keep?>', '<?audit changed?>'), ('<!--inner-->', '<!--changed-->')]:
            self.check(dict(request(), after=packed(FORMATTED.replace(source, target))), 'whole target XML differs')

    def test_zip_metadata(self):
        self.check(dict(request(), after=packed(FORMATTED, comment=b'changed')), 'ZIP archive comment')

    def test_layout_removal_is_exact(self):
        stale = FORMATTED.replace('</p:p><p:p><!--inner-->', '<p:linesegarray><p:lineseg vertpos="123"/></p:linesegarray></p:p><p:p><!--inner-->')
        self.check(dict(request(), after=packed(stale)), 'whole target XML differs')
        self.check(dict(request(), invalidateLineSegments=False), 'whole target XML differs')

    def test_empty_owner_style(self):
        wrong = FORMATTED.replace("<p:run charPrIDRef='1'><p:t/>", "<p:run charPrIDRef='2'><p:t/>")
        self.check(dict(request(), after=packed(wrong)), 'whole target XML differs')

    def test_empty_owner_loss(self):
        self.check(dict(request(), after=packed(FORMATTED.replace('<p:t/>', ''))), 'whole target XML differs')

    def test_field_control_duplication(self):
        marker = "<p:ctrl><p:fieldEnd beginIDRef='1'/></p:ctrl>"
        self.check(dict(request(), after=packed(FORMATTED.replace(marker, marker + marker))), 'whole target XML differs')

    def test_source_plus_two_commands(self):
        self.check(dict(request(), mode='per-text-format-and-replace', after=packed(SPLICED), leftBefore='B', rightBefore='C', inserted='Y', deleteUnits=1))
        self.check(dict(request(), mode='per-text-format-and-replace', after=packed(SPLICED), leftBefore='B', rightBefore='C', inserted='Z', deleteUnits=1), 'whole target XML differs')

    def test_unchanged_requested_style(self):
        expected = XML.replace('<p:linesegarray><p:lineseg vertpos="123"/></p:linesegarray>', '')
        self.check(dict(request(), charShapeId=1, after=packed(expected)))

    def test_duplicate_entry(self):
        self.check(dict(request(), after=packed(FORMATTED, duplicate=True)), 'ZIP inventory/order/duplicate')


if __name__ == '__main__':
    import sys
    unittest.main()
